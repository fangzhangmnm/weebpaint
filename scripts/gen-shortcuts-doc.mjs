#!/usr/bin/env node
// gen-shortcuts-doc.mjs — regenerates docs/shortcuts.md from the KEYBOARD_SHORTCUTS table
// in src/input.ts (the same table the in-app menu → "Shortcuts" panel renders) plus the
// English labels in src/i18n/strings.ts. Pure text extraction; no app code is executed.
// Usage: node scripts/gen-shortcuts-doc.mjs
// created by Claude Fable 5 · 2026-08-28

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const input = readFileSync(join(root, "src/input.ts"), "utf8");
const strings = readFileSync(join(root, "src/i18n/strings.ts"), "utf8");
const version =
  readFileSync(join(root, "src/version.ts"), "utf8").match(/WEEBPAINT_VERSION\s*=\s*"([^"]+)"/)?.[1] ?? "unknown";

const start = input.indexOf("export const KEYBOARD_SHORTCUTS");
const end = input.indexOf("\n];", start);
if (start < 0 || end < 0) throw new Error("KEYBOARD_SHORTCUTS table not found in src/input.ts");
const table = input.slice(start, end);

const entries = [];
const entryRe = /\{\s*combo:\s*"([^"]+)",\s*desc:\s*"([^"]+)",\s*category:\s*"([^"]+)"/g;
for (let m; (m = entryRe.exec(table)); ) entries.push({ combo: m[1], desc: m[2], category: m[3] });
if (entries.length < 20)
  throw new Error(`only ${entries.length} shortcuts extracted — table format changed? fix this script`);

const en = new Map();
const strRe = /"([A-Za-z0-9_.-]+)":\s*\{[^}]*?\ben:\s*"([^"]*)"/g;
for (let m; (m = strRe.exec(strings)); ) en.set(m[1], m[2]);
const missing = new Set();
const t = (key) => {
  if (!en.has(key)) missing.add(key);
  return en.get(key) ?? key;
};

// Group by category in first-seen order; within a category, merge combos that share a desc.
const cats = new Map();
for (const e of entries) {
  if (!cats.has(e.category)) cats.set(e.category, new Map());
  const rows = cats.get(e.category);
  if (!rows.has(e.desc)) rows.set(e.desc, []);
  const combos = rows.get(e.desc);
  if (!combos.includes(e.combo)) combos.push(e.combo);
}

let md = `<!-- AUTO-GENERATED by scripts/gen-shortcuts-doc.mjs — do not edit by hand. -->\n\n`;
md += `# Keyboard shortcuts\n\n`;
md += `> generated from \`src/input.ts\` (the same table the in-app menu → "Shortcuts" panel renders) · ${version}\n\n`;
for (const [cat, rows] of cats) {
  md += `## ${t(cat)}\n\n| Keys | Action |\n|---|---|\n`;
  for (const [desc, combos] of rows)
    md += `| ${combos.map((c) => `\`${c}\``).join(" / ")} | ${t(desc)} |\n`;
  md += `\n`;
}
md += `## Touch gestures\n\n| Gesture | Action |\n|---|---|\n`;
md += `| Two-finger pinch | Zoom / rotate the canvas |\n`;
md += `| Two-finger tap | Undo |\n`;
md += `| Three-finger tap | Redo |\n`;

writeFileSync(join(root, "docs/shortcuts.md"), md);
if (missing.size) console.error(`WARN: missing en strings for: ${[...missing].join(", ")}`);
console.log(`docs/shortcuts.md written: ${entries.length} shortcuts, ${cats.size} categories`);
